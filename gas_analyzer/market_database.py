def build_dataframe() -> pd.DataFrame:
    """Зібрати все в єдиний датафрейм (місячний)."""
    idx = pd.date_range("2024-01-01", "2026-03-01", freq="MS")
    df = pd.DataFrame(index=idx)

    # TTF EUR/MWh
    ttf = pd.Series({pd.Timestamp(k+"-01"): v for k, v in TTF_MONTHLY_EUR.items()})
    df["ttf_eur_mwh"] = ttf.reindex(idx)

    # TTF → UAH/1000m3 (через фіксований курс 42 UAH/EUR)
    df["ttf_uah_thcm"] = df["ttf_eur_mwh"] * UAH_EUR_RATE * MWH_PER_THCM

    # UEEX UAH/1000m3
    ueex = pd.Series({pd.Timestamp(k+"-01"): v for k, v in UEEX_MONTHLY_UAH.items()})
    df["ueex_uah_thcm"] = ueex.reindex(idx)

    # UEEX premium over TTF import parity (%)
    df["ueex_premium_pct"] = (df["ueex_uah_thcm"] / df["ttf_uah_thcm"] - 1) * 100

    # Імпорт
    imp = pd.Series({pd.Timestamp(k+"-01"): v for k, v in IMPORT_MCM.items()})
    df["import_mcm"] = imp.reindex(idx)

    return df


